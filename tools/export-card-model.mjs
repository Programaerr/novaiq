/**
 * Exports the NOVAIQ credential card as a 3D model, for Blender and for a 3D printer.
 *
 *   node tools/export-card-model.mjs
 *
 * Writes to `model/`:
 *   novaiq-card.stl  — binary STL, the printable solid. STL is what slicers read; it carries
 *                      triangles and nothing else, which is all a printer can use.
 *   novaiq-card.obj  — the same mesh WITH its UV coordinates, so the artwork can be applied in
 *                      Blender as a texture, a decal or a displacement map.
 *
 * ## Why this file rebuilds the geometry instead of importing the component
 *
 * The card's shape lives in a React component that also loads images, draws to a 2D canvas and
 * expects a browser. None of that exists in Node and none of it is the shape. The eight numbers
 * below ARE the card — they are copied from CredentialCard3D.tsx and are the only thing the two
 * have to agree on. If the card's proportions ever change there, change them here too.
 *
 * ## Scale
 *
 * The scene worked in arbitrary units where the card was 1.586 wide. A printer works in
 * millimetres, so everything is multiplied out to ISO/IEC 7810 ID-1 — 85.6 x 54mm, the size of
 * every bank and ID card in the world, which is what makes the printed object feel like a card in
 * the hand rather than a plaque.
 *
 * The one dimension deliberately NOT to scale is the thickness. A real ID-1 card is 0.76mm, and at
 * that thickness an FDM print is two or three layers — it warps coming off the bed and snaps in a
 * pocket. 2.7mm is what the scene's own proportion gives, it prints solidly, and it reads as a
 * heavier, better version of a card rather than a wrong one.
 */
import * as THREE from 'three';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

// ── The card, exactly as the site builds it ────────────────────────────────────────────────
const CARD_W = 1.586;
const CARD_H = 1;
const CARD_D = 0.05;
const CARD_R = 0.1;
const BEVEL = 0.006;

/** Scene units to millimetres: 85.6mm across the long edge is ID-1. */
const MM_PER_UNIT = 85.6 / CARD_W;

function buildCardGeometry() {
  const w = CARD_W / 2;
  const h = CARD_H / 2;
  const r = CARD_R;

  const shape = new THREE.Shape();
  shape.moveTo(-w + r, -h);
  shape.lineTo(w - r, -h);
  shape.quadraticCurveTo(w, -h, w, -h + r);
  shape.lineTo(w, h - r);
  shape.quadraticCurveTo(w, h, w - r, h);
  shape.lineTo(-w + r, h);
  shape.quadraticCurveTo(-w, h, -w, h - r);
  shape.lineTo(-w, -h + r);
  shape.quadraticCurveTo(-w, -h, -w + r, -h);

  const geo = new THREE.ExtrudeGeometry(shape, {
    depth: CARD_D,
    bevelEnabled: true,
    bevelSize: BEVEL,
    bevelThickness: BEVEL,
    bevelSegments: 2,
    // Higher than the site's 14. On screen the corners are a few dozen pixels and 14 segments is
    // already past what a display can resolve; printed at 85mm they are a thumb's width across and
    // faceting is something you can feel. Segments are free here — this runs once, offline.
    curveSegments: 48,
  });

  // Centred on z = 0, then laid flat and scaled to millimetres. Flat matters for printing: a card
  // standing on its edge needs supports and prints its faces as visible layer lines, whereas
  // lying down it prints as one clean sweep with the artwork face up.
  geo.translate(0, 0, -CARD_D / 2);
  geo.rotateX(-Math.PI / 2);
  geo.scale(MM_PER_UNIT, MM_PER_UNIT, MM_PER_UNIT);
  geo.computeVertexNormals();
  return geo.toNonIndexed();
}

/**
 * Binary STL, written by hand rather than through three's STLExporter.
 *
 * The exporter lives under `three/examples/`, which the package's own `exports` map does not
 * publish — importing it from Node is a path that may or may not resolve depending on the version.
 * The format itself is an 80-byte header, a triangle count, and 50 bytes per triangle. Writing it
 * directly is a dozen lines and cannot break on a dependency update.
 */
function toBinarySTL(geometry) {
  const pos = geometry.getAttribute('position');
  const nor = geometry.getAttribute('normal');
  const triangles = pos.count / 3;

  const buffer = Buffer.alloc(84 + triangles * 50);
  buffer.write('NOVAIQ credential card - ISO ID-1 - generated by tools/export-card-model.mjs', 0, 80, 'ascii');
  buffer.writeUInt32LE(triangles, 80);

  let o = 84;
  for (let t = 0; t < triangles; t++) {
    const a = t * 3;
    // One normal per facet: STL has no per-vertex normals, so the first vertex's is used for all
    // three. Slicers recompute winding anyway; this field is effectively a formality.
    buffer.writeFloatLE(nor.getX(a), o); o += 4;
    buffer.writeFloatLE(nor.getY(a), o); o += 4;
    buffer.writeFloatLE(nor.getZ(a), o); o += 4;
    for (let v = 0; v < 3; v++) {
      buffer.writeFloatLE(pos.getX(a + v), o); o += 4;
      buffer.writeFloatLE(pos.getY(a + v), o); o += 4;
      buffer.writeFloatLE(pos.getZ(a + v), o); o += 4;
    }
    buffer.writeUInt16LE(0, o); o += 2; // attribute byte count, unused
  }
  return buffer;
}

/** Wavefront OBJ — keeps the UVs, which STL cannot carry and Blender needs for the artwork. */
function toOBJ(geometry) {
  const pos = geometry.getAttribute('position');
  const uv = geometry.getAttribute('uv');
  const nor = geometry.getAttribute('normal');
  const out = ['# NOVAIQ credential card', '# generated by tools/export-card-model.mjs', 'o NovaiqCard'];

  for (let i = 0; i < pos.count; i++) out.push(`v ${pos.getX(i).toFixed(4)} ${pos.getY(i).toFixed(4)} ${pos.getZ(i).toFixed(4)}`);
  if (uv) for (let i = 0; i < uv.count; i++) out.push(`vt ${uv.getX(i).toFixed(5)} ${uv.getY(i).toFixed(5)}`);
  for (let i = 0; i < nor.count; i++) out.push(`vn ${nor.getX(i).toFixed(4)} ${nor.getY(i).toFixed(4)} ${nor.getZ(i).toFixed(4)}`);

  for (let t = 0; t < pos.count / 3; t++) {
    const [a, b, c] = [t * 3 + 1, t * 3 + 2, t * 3 + 3]; // OBJ indices are 1-based
    out.push(uv ? `f ${a}/${a}/${a} ${b}/${b}/${b} ${c}/${c}/${c}` : `f ${a}//${a} ${b}//${b} ${c}//${c}`);
  }
  return out.join('\n') + '\n';
}

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'model');
mkdirSync(outDir, { recursive: true });

const geometry = buildCardGeometry();
const box = new THREE.Box3().setFromBufferAttribute(geometry.getAttribute('position'));
const size = box.getSize(new THREE.Vector3());

writeFileSync(join(outDir, 'novaiq-card.stl'), toBinarySTL(geometry));
writeFileSync(join(outDir, 'novaiq-card.obj'), toOBJ(geometry));

console.log('model/novaiq-card.stl  + .obj');
console.log(`  ${(geometry.getAttribute('position').count / 3).toLocaleString()} triangles`);
console.log(`  ${size.x.toFixed(2)} x ${size.z.toFixed(2)} x ${size.y.toFixed(2)} mm  (W x D x thickness)`);
