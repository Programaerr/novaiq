/**
 * قانون رقم الهاتف العراقي — تعريف واحد يستعمله كل حقل هاتف في الموقع.
 *
 * ## لماذا وحدة مستقلة
 *
 * كان القانون مكتوباً مرّتين بصيغتين مختلفتين: منشئ العقود يقبل `07` و11 رقماً فقط ويمنع
 * إدخال أي حرف أصلاً، ونموذج التواصل يقبل معها صيغة `+964` "لأنها لمسة أولى لا وثيقة موقّعة"
 * ولا يمنع شيئاً أثناء الكتابة. النتيجة: نفس الرقم يُقبل في شاشة ويُرفض في أخرى، وصاحبه لا
 * يعرف أيّهما القانون. قانونان لشيء واحد ليسا مرونة، هما عطل يظهر متأخراً.
 *
 * ## القانون
 *
 * أرقام فقط، 11 رقماً، تبدأ بـ 07. لا حروف، ولا مسافات، ولا `+964`، ولا رمز دولة.
 *
 * ## ويُفرَض عند الكتابة لا عند الإرسال
 *
 * `sanitizeIraqiPhone` تُستدعى في `onChange` كل حقل: الحرف لا يُكتب أصلاً، والرقم الثاني عشر
 * لا يدخل. تحقّق يقع عند الضغط على "إرسال" وحده يعني أن الخطأ يُكتشف بعد أن يكمل الزائر
 * النموذج كله — بينما المنع عند الكتابة يجعل الحقل الخاطئ مستحيلاً لا مرفوضاً.
 */

/** طول الرقم العراقي كاملاً. */
export const IRAQI_PHONE_LENGTH = 11;

/** أرقام فقط، ومقصوصة عند الطول القانوني. تُستدعى في onChange لا في التحقق وحده. */
export function sanitizeIraqiPhone(raw: string): string {
  return raw.replace(/\D/g, '').slice(0, IRAQI_PHONE_LENGTH);
}

/** الصيغة الوحيدة المقبولة: 07 ثم تسعة أرقام. */
export function isValidIraqiPhone(raw: string): boolean {
  return /^07\d{9}$/.test(sanitizeIraqiPhone(raw));
}

