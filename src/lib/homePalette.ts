/**
 * يحوّل أي رمز أعلاه إلى ثلاثي قنوات مفصول بمسافات (مثل `255 142 61`) — الشكل الوحيد
 * اللي يقبله `rgb(var(--x) / 0.25)` بـ Tailwind، لمّا متغير CSS لازم يحمل لوناً وتُضاف
 * له شفافية عند الاستخدام.
 *
 * موجودة لأن الفوتر كان يكتب هذا الثلاثي باليد: `'255 106 0'`. ولأنها مو هيئة hex،
 * ما طلعت بأي بحث عن لون العلامة، فضلّت ترسم البرتقالي القديم بعد ما تحرّك كل سطح ثاني.
 * الاشتقاق يمنع تكرارها.
 */
export function channels(hex: string): string {
  const h = hex.replace('#', '');
  const full = h.length === 3 ? h.split('').map((c) => c + c).join('') : h;
  return [0, 2, 4].map((i) => parseInt(full.slice(i, i + 2), 16)).join(' ');
}
